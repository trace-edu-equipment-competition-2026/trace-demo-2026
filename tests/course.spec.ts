  await page.getByRole('button',{name:'과목 설정',exact:true}).click()
  await page.getByRole('button',{name:/학교 시스템에서 불러오기/}).click()
  await page.getByRole('button',{name:'NEIS에서 불러오기',exact:true}).click()
