  await modal.getByLabel('과목 기본 정보 추출 내용').fill('정보 네트워크 실습')
  await modal.getByLabel('학습 목표 추출 내용').fill('설정과 검증을 연결해 설명한다.')
  await modal.getByLabel('평가 요소 추출 내용').fill('문제 이해 | 40\n검증 | 40\n협업 | 20')
