    if(width<=1050)await page.getByRole('button',{name:'수업 메뉴 열기'}).click()
    await page.getByRole('button',{name:'수업 대시보드',exact:true}).click()
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
